Agent::ToolRegistry.register(
  name: 'get_random_phrase',
  description: 'Возвращает JSON-массив из 10 случайных фраз — юмористические ругательства и обзывания, добавленные участниками чата командой "бот, ты X". Выбери из них наиболее подходящую к ситуации. Используй когда хочешь ответить в духе внутренних шуток чата, когда запрос абсурдный или риторический, или когда просто хочешь добавить хаоса вместо серьёзного ответа.',
  parameters: {},
  handler: ->(args, ctx) {
    phrases = Phrase.order("random()").limit(10).pluck(:content)
    phrases.empty? ? "фраз нет" : phrases.to_json
  }
)
