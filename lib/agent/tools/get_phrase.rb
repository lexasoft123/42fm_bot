Agent::ToolRegistry.register(
  name: 'get_random_phrase',
  description: 'Возвращает случайную фразу из коллекции — юмористические ругательства и обзывания, добавленные участниками чата командой "бот, ты X". Используй когда хочешь ответить в духе внутренних шуток чата, когда запрос абсурдный или риторический, или когда просто хочешь добавить хаоса вместо серьёзного ответа.',
  parameters: {},
  handler: ->(args, ctx) {
    phrase = Phrase.order("random()").first
    phrase ? phrase.content : "фраз нет"
  }
)
